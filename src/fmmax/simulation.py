import jax
import torch
from dataclasses import dataclass
from pathlib import Path
from typing import Any

# Enable double precision before creating JAX arrays
jax.config.update("jax_enable_x64", True)

from src.fmmax.config import FMMaxConfig
from src.fmmax import basis, fmm, scattering

@dataclass
class FMMaxModel:
    """Physical description of the physical structure

    Lengths are in nanometers, angles are stored in degrees
    and converted by each solver adapter as required.

    FMMax objects are prepared from one solver independent 
    MetaRCWA model.

    This dataclass stores the intermediate objects needed for a
    FMMax simulation. Class used because named fields are clearer
    than returning a long tuple whose meaning depends on the order
    of the position.

    Attributes
    ----------

    config:
        Numerical settings translated into FMMax compatible settings
    model_spec:
        MetaRCWA model after material evaluation and geometry rasterisation.
    lattice_vectors:
        Primitive lattice vectors u and v for the FMMax simulation
    expansion:
        Reciprocal-space Fourier basis generated by FMMax
    wavelength:
        Wavelength(s) of the incident light in nanometers
    in_plane_wavevector:
        In-plane wavevector of the incident light in reciprocal space units
    incidence_eps:
        Incidence medium permittivity array for the FMMax simulation.
    transmission_eps:
        Transmission medium permittivity array for the FMMax simulation.
    permittivities:
        List of permittivity arrays for the complete stack in physical order, 
        including incidence and transmission media.
    thicknesses:
        List of thickness arrays for the complete stack in physical order,
        including incidence and transmission media.
    layer_solve_results:
        FMMax electromagnetic eigenmode solutions for every layer in the stack, 
        including incidence and transmission media.
    s_matrix:
        FMMax scattering matrix for the complete stack, including incidence and transmission media.
    """

    config: FMMaxConfig
    model_spec: Any
    lattice_vectors: basis.LatticeVectors
    expansion: basis.Expansion
    wavelength: jax.Array
    in_plane_wavevector: jax.Array
    incidence_eps: jax.Array
    transmission_eps: jax.Array
    permittivities: list[jax.Array]
    thicknesses: list[jax.Array]
    layer_solve_results: list[fmm.LayerSolveResult]
    s_matrix: scattering.ScatteringMatrix