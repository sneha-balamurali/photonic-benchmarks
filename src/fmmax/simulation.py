from metarcwa.model.layer import HomogeneousLayer, PatternedLayer


def torch_to_jax(value: torch.Tensor, 
                dtype:type,) -> Any:
    """Converts a MetaRCWA torch tensor into a JAX array.
    
    MetaRCWA uses PyTorch tensors, whereas FMMax uses JAX arrays.
    This conversion is necessary to run the FMMax solver on the same model.
    
    This function uses detach() to remove PyTorch's gradient tracking
    because a tensor connected to a computation graph cannot be converted 
    to a NumPy array. It then passes the tensor into CPU memory if it is
    currently on a GPU. This is because NumPy does not support GPU tensors.

    It is then converted to a NumPy array because both PyTorch and JAX understand 
    NumPy's in-memory array format. The NumPy conversion gives a predictable
    CPU array that can be passed into JAX's jnp.asarray() function to create a JAX array.

    Something I want to explore later is DLPack, which allows JAX to use 
    PyTorch tensors directly but for simple conversion, this is a good first step.

    Parameters
    ----------
    value: 
        Pytorch tensor to be converted into a JAX array.
    dtype:
        The desired data type for the JAX array.
    
    Returns
    -------
    Any:
        JAX array with the same data as the input tensor,
        but in the specified dtype.
    """ 

    numpy_value = value.detach().cpu().numpy()

    jax_array = jnp.asarray(numpy_value, dtype=dtype)

    return jax_array

def prepare_uniform_permittivity(value: torch.Tensor,
                                complex_dtype:type) -> jnp.ndarray:
    """Convert MetaRCWA uniform permittivity for batched FMMax calculations. 

    MetaRCWA stores an isotropic medium's permittivity as one complex value
    per wavelength, with shape (Nw).

    FMMax treats the final two dimension of a permittivity array as the spatial
    unit-cell grid. A spatially uniform medium is represented by a 
    one-by-one grid so the the final dimensions has to be (1,1).

    This framework tries to preserve MetaRCWA's independent wavelength, theta, phi,
    sweep axes. The permittivity depends on wavelength but not on illumination angles. 
    So the length one theta and phi dimensions are just inserted as broadcasting
    placeholders. 

    Conversion:
    (Nw,) -> (Nw,1,1,1,1)

    The returned dimensions represent:
    (wavelength, theta placeholder, phi placeholder, spatial axis 0, spatial axis 1)

    A dimension of length one tells JAX that the same material value can be reused
    across that axis. So, each wavelength depended permittivity is reused for every
    theta, phi and every spatial point in the uniform medium.

    ** For a patterned layer, the returned one by one spatial material arrays can later broadcast 
    against a pattern with shape.

    (Ngrid0, Ngrid1)

    Parameters
    ----------
    value:
        Complex MetaRCWA permittivity tensor with shape (Nw)
    complex_dtype:
        JAX complex dtype selected by FMMaxConfig, normally 
        jnp.complex64 or jnp.complex128

    Returns
    --------
    jax.Array:
        Complex JAX permittivity array with shape
        (Nw, 1,1,1,1)
    """                            

    converted = torch_to_jax(value, dtype=complex_dtype)

    return converted.reshape(-1, 1, 1, 1, 1)
    

@dataclass
class PreparedFMMaxModel:
    """FMMax objects are prepared from one solver independent MetaRCWA model.

    This dataclass stores the intermediate objects needed for a FMMax simulation.
    Class used because named fields are clearer than returning a long tuple whos meaning depends on
    the order of the position. 

    Attribute:
    ----------
    config: 
        Numerical settings translated into FMMax-compatible settings. 
    model_spec:
        MetaRCWA model after material evaluation and geometry rasterisation.
    lattice_vectors:
        Primitive lattice vectors u and v for the FMMax simulation.
    expansion:
        Reciprocal-space Fourier basis generated by FMMax.
    wavelength:
        Wavelength array 
    in_plane_wavector:
        In-plane wavevector array (kx, ky) for the FMMax simulation.
    incidence_eps:
        Incidence medium permittivity array for the FMMax simulation.
    transmission_eps:
        Transmission medium permittivity array for the FMMax simulation.
    permittivities:
        List of permittivity arrays for the complete stack in physical order, 
        including incidence and transmission media.
    thicknesses:
        List of thickness arrays for the complete stack in physical order,
        including incidence and transmission media.
    layer_solve_results:
        FMMax electromagnetic eigenmode solutions for every layer in the stack, 
        including incidence and transmission media.
    s_matrix:
        FMMax scattering matrix for the complete stack, including incidence and transmission media.
    """

    config: FMMaxConfig
    model_spec: Any
    lattice_vectors: basis.LatticeVectors
    expansion: basis.Expansion
    wavelength: jax.Array
    in_plane_wavevector: jax.Array
    incidence_eps: jax.Array
    transmission_eps: jax.Array
    permittivities: list[jax.Array]
    thicknesses: list[jax.Array]
    layer_solve_results: list[fmm.LayerSolveResult]
    s_matrix: scattering.ScatteringMatrix

    @classmethod
    def from_model(
        cls,
        model: Model,
        config: Config
        ) ->"PreparedFMMaxModel": 
        """Translate a MetaRCWA model into FMMax simulation objects.
        
        This method:

        - translates the common numerical configuration
        - resolves and rasterises the MetaRCWA model
        - converts PyTorch tensors into JAX arrays
        - prepares wavelength and angle batch dimensions
        - creates the FMMax lattice and Fourier expansion
        - constructs homoegeneous and patterned permittivity arrays
        - solves the electromagnetic modes of every layer
        - builds the scattering matrix for the complete stack
        """

        cfg = FMMaxConfig.from_config(config)

        # Resolve wavelength-dependent material values and rasterise
        # the pattern onto the requested nx by ny grid
        model_spec = model.spec(nx=cfg.nx,
                                ny=cfg.ny
        )

        # MetaRCWA calls these vectors a1 and a2. FMMax calls the
        # equivalent primitive lattice vectors u and v
        lattice_vectors = basis.LatticeVectors(
            u=torch_to_jax(model_spec.a1, dtype=cfg.real_dtype),
            v=torch_to_jax(model_spec.a2, dtype=cfg.real_dtype)
        )

        # MetaRCWA provides shape (Nw,), while kx0 and ky0 use 
        # (Nw, Ntheta, Nphi). Add length-one theta and phi axes so
        # JAX reuses each wavelength across every angle
        # (Nw,) goes to (Nw,1,1)
        wavelength = torch_to_jax(model_spec.wavelength, dtype=cfg.real_dtype).reshape(-1,1,1)

        # MetaRCWA stores kx0 and ky0 are normalised by the free-space 
        # wavenumber but FMMax expects the physical in-plane wavevector
        free_space_wavenumber = 2 * jnp.pi / wavelength

        kx = (
            torch_to_jax(model_spec.kx0, dtype=cfg.real_dtype) 
            *
            free_space_wavenumber
        )

        ky = (
            torch_to_jax(model_spec.ky0, dtype=cfg.real_dtype)
            *
            free_space_wavenumber
        )

        # FMMax requires the final dimension to contain the [kx,ky]
        # Confirm in fmm.py in FMMax line 964. 
        # Recall:
        # kx0 and ky0: (Nw, Ntheta, Nphi)
        # kx and ky: (Nw, Ntheta, Nphi)
        # in_plane_wavevector: (Nw, Ntheta, Nphi, 2)
        in_plane_wavevector = jnp.stack([kx,ky], axis=-1)

        # FMMax requires uniform media to have final spatial dimension
        # of (1,1)
        # incidence_eps.shape = (Nw,1,1,1,1)
        # transmission_eps.shape - (Nw,1,1,1,1)

        incidence_eps = prepare_uniform_permittivity(
            model_spec.incidence.eps, complex_dtype = cfg.complex_dtype
        )

        transmission_eps = prepare_uniform_permittivity(
            model_spec.transmission.eps, complex_dtype=cfg.complex_dtype
        )

        layer_permittivities = []
        layer_thicknesses = []

        for layer in model_spec.layers:
            thickness = torch_to_jax(layer.thickness, dtype=cfg.real_dtype)
            # A scale thickness has shape ()
            layer_thicknesses.append(thickness)

            if isinstance(layer, HomogeneousLayer):
                # Output shape: (Nw,1,1,1,1)
                permittivity = prepare_uniform_permittivity(
                    layer.medium.eps,
                    complex_dtype=cfg.complex_dtype
                )
            elif isinstance(layer, PatternedLayer):
                # A patterned layer contains:
                # - a solid material
                # - a void/background material
                # - a spatial mask selecting between them
                # Output shape: (Nw,1,1,1,1)
                # Each material initially varies only with 
                # wavelength
                solid_eps = prepare_uniform_permittivity(
                    layer.medium_solid.eps,
                    complex_dtype=cfg.complex_dtype
                )
                void_eps = prepare_uniform_permittivity(
                    layer.medium_void.eps,
                    complex_dtype=cfg.complex_dtype
                )

                # Pattern shape: (Ngrid0, Ngrid1)
                pattern = torch_to_jax(
                    layer.pattern,
                    dtype = cfg.real_dtype
                )

                # Combine the two materials and pattern into one
                # spatial permittivity grid for the FMMax eigensolver
                # density = 1 selects the solid material
                # density = 0 selects the void material

                # Broadcasting combines:
                # solid_eps: (Nw,1,1,1,     1)
                # void_eps: (Nw,1,1,1,      1)
                # pattern:              (Ngrid0,Ngrid1)
                # result: (Nw,1,1,Ngrid0,Ngrid1)
                permittivity = utils.interpolate_permittivity(
                    permittivity_solid = solid_eps,
                    permittivity_void=void_eps,
                    density = pattern
                )

            else:
                # Raise error if the layers are not
                # supported by the layer classes translated above
                raise TypeError(
                    "Unsupported MetaRCWA layer type:"
                    f"{type(layer).__name__}"
                )
            layer_permittivities.append(permittivity)
            
        # Complete incidence to transmission stack
        permittivities = [
            incidence_eps,
            *layer_permittivities,
            transmission_eps
        ]
        # The two end media are semi-infinite and therefore dont have
        # finite propagation thickness.
        zero_thickness = jnp.asarray(0.0,
                                    dtype=cfg.real_dtype)
        
        thicknesses = [zero_thickness, *layer_thicknesses, zero_thickness]

        # Generate the reciprocal-space Fourier basis shared by every layer
        # Shape = (Nterms, 2)
        expansion = basis.generate_expansion(
            primitive_lattice_vectors = lattice_vectors,
            approximate_num_terms = cfg.approximate_num_terms,
            truncation = cfg.truncation
        )

        # Solve the electromagnetic modes independently in every medium 
        # finite layer
        layer_solve_results = [
            fmm.eigensolve_isotropic_media(
                wavelength=wavelength,
                in_plane_wavevector=in_plane_wavevector,
                primitive_lattice_vectors=lattice_vectors,
                permittivity=permittivity,
                expansion=expansion,
                formulation=cfg.formulation
            )
            for permittivity in permittivities
        ]

        # Combine the individual layer solutions into one scattering matrix
        # for the complete stack
        s_matrix = scattering.stack_s_matrix(
            layer_solve_results=layer_solve_results,
            layer_thicknesses = thicknesses
        )

        #cls(...) constructs and returns one PreparedFMMaxModel object
        return cls(
            config=cfg,
            model_spec=model_spec,
            lattice_vectors=lattice_vectors,
            expansion=expansion,
            wavelength=wavelength,
            in_plane_wavevector=in_plane_wavevector,
            incidence_eps=incidence_eps,
            transmission_eps=transmission_eps,
            permittivities=permittivities,
            thicknesses=thicknesses,
            layer_solve_results=layer_solve_results,
            s_matrix=s_matrix,
        )
